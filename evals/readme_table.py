"""Writes the eval score table into README.md from claude plugin eval results.

    python evals/readme_table.py <results.json> [<results.json> ...]

Each file is the --json output of one with-without run (the same schema as
aggregate-result.json). Several files can be combined, for suites run in batches,
as long as they used the same model, Claude Code version and runs per case. The
table replaces everything between the eval-table markers in README.md.
"""

import json
import sys
from pathlib import Path

README = Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- eval-table:start -->"
END = "<!-- eval-table:end -->"
WHOLE_PROGRAM = "port-sample"


def load(paths):
    cases, models, versions, dates = {}, set(), set(), set()
    for path in paths:
        result = json.loads(Path(path).read_text(encoding="utf-8"))
        if result.get("partial"):
            sys.exit(f"{path} is partial: the run stopped early, so its scores are incomplete")
        if result["suite"].get("ablation") != "with-without":
            sys.exit(f"{path} has no without-skill arm: run it with --ablation with-without")
        models.add(result["suite"].get("modelOverride"))
        versions.add(result["claudeVersion"])
        dates.add(result["startedAt"][:10])
        for case in result["cases"]:
            if case["name"] in cases:
                sys.exit(f"{case['name']} appears in more than one results file")
            cases[case["name"]] = case
    if len(models) != 1 or len(versions) != 1:
        sys.exit(f"The results mix models {sorted(map(str, models))} or Claude Code versions {sorted(versions)}")
    return cases, models.pop(), versions.pop(), sorted(dates)


def row(case):
    runs = case["arms"]["with"]
    fired = sum(
        1 for run in runs for grader in run.get("graders", []) if grader["name"] == "skill-fired" and grader["passed"]
    )
    totals = case["aggregates"]
    name = "Whole program (`samples/bounce`)" if case["name"] == WHOLE_PROGRAM else f"`{case['name']}`"
    return (f"| {name} | {totals['score']:.2f} | {totals['scoreWithout']:.2f} | {totals['delta']:+.2f} "
            f"| {fired} of {len(runs)} |")


def table(cases, model, version, dates):
    runs = {len(case["arms"]["with"]) for case in cases.values()}
    if len(runs) != 1:
        sys.exit(f"Cases ran different numbers of times: {sorted(runs)}")
    order = sorted(name for name in cases if name != WHOLE_PROGRAM)
    if WHOLE_PROGRAM in cases:
        order.append(WHOLE_PROGRAM)
    when = " to ".join([dates[0], dates[-1]] if len(dates) > 1 else dates)
    count = runs.pop()
    lines = [
        "| Case | With skill | Without skill | Difference | Skill fired |",
        "|---|---|---|---|---|",
        *(row(cases[name]) for name in order),
        "",
        f"`{model}`, Claude Code {version}, {count} run{'s' if count != 1 else ''} per case, {when}. A score is "
        "the share of a case's graders that passed, not counting `skill-fired`, averaged over its runs. "
        "Generated by `evals/readme_table.py`.",
    ]
    return "\n".join(lines)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"README.md has no {START} ... {END} block")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    new = f"{before}{START}\n{table(*load(sys.argv[1:]))}\n{END}{after}"
    README.write_text(new, encoding="utf-8", newline="\n")
    print(f"Updated the eval table in {README}")


if __name__ == "__main__":
    main()
